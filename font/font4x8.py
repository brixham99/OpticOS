def nibble(row: str) -> int:
    n = 0
    for i, p in enumerate(row):
        if p == "#":
            n |= 1 << (3 - i)
    return n


def glyph_rows(code: int) -> tuple[str, ...]:
    if not 32 <= code <= 127:
        raise ValueError(f"font covers 32-127, not {code}")
    return GLYPHS[chr(code)]
