#!/usr/bin/env python3
"""Build build/opticos128ext.rom (the 128K extension ROM for ROM slot 1) from ext128/screen.asm.
Needs build/opticos.rom / .sym first (./build.sh): OpticOS addresses come from its symbol file."""
import os, re, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sym = {m[1]: int(m[2], 16) for m in re.finditer(r'(\w+)\s+EQU\s+0?([0-9A-F]+)H', open(os.path.join(ROOT, 'build', 'opticos.sym')).read())}
NEED = ['boot', 'ext_back', 'xgo', 'x_rst', 'id_skip', 'ev_expr', 'pop_int', 'push_u', 'err_rng', 'err_syn', 'CLS']
open(os.path.join(HERE, 'os.inc'), 'w').write('; generated by ext128/build.py from build/opticos.sym\n' +
    ''.join('OS_%s equ $%04X\n' % (k, sym[k]) for k in NEED))
def ta(i):
    ink, paper = i >> 4, i & 15
    br = (ink & 8) if (ink & 7) else (paper & 8)
    return (64 if br else 0) | (paper & 7) << 3 | (ink & 7)
db = lambda vals: ''.join('        db ' + ','.join('$%02X' % v for v in vals[i:i + 16]) + '\n' for i in range(0, len(vals), 16))
open(os.path.join(HERE, 'ta.inc'), 'w').write(db([ta(i) for i in range(256)]))
open(os.path.join(HERE, 'ta2.inc'), 'w').write(db([(64 if c & 8 else 0) | (c & 7) << 3 | (c & 7) for c in range(16)]))
out = os.path.join(ROOT, 'build', 'opticos128ext')
subprocess.run(['pasmo', '--bin', 'screen.asm', out + '.bin', out + '.sym'], check=True, cwd=HERE)
rom = open(out + '.bin', 'rb').read(); assert len(rom) <= 16384, len(rom)
open(out + '.rom', 'wb').write(rom + bytes(16384 - len(rom))); os.remove(out + '.bin')
end = {m[1]: int(m[2], 16) for m in re.finditer(r'(\w+)\s+EQU\s+0?([0-9A-F]+)H', open(out + '.sym').read())}
print('opticos128ext.rom: code $1000-$%04X, %d bytes free' % (end['n_point'] + 6, 0x3E00 - (end['n_point'] + 6) + (0x3F00 - 0x3E10)))
