#!/usr/bin/env python3
"""Build build/opticos128ext.rom: SAY and SCREEN merged into one 128K
extension ROM for slot 1.  Starts from the generated SAY source in
/workspace/opticos-speech/src/ext128.asm, retargets OpticOS addresses
from this tree's build/opticos.sym, plants the screen-mode hooks, and
includes ext128/screen.asm (PLOT/DRAW/BOX/CIRCLE/CLS/POINT/SCREEN/FLIP) before
the AY volume table at $3D00."""
import os, re, subprocess, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SAY_SRC = os.environ.get('SAY_EXT_SRC', '/workspace/opticos-speech/src/ext128.asm')
PASMO = os.environ.get('PASMO', '/workspace/tools-prefix/usr/bin/pasmo')
AYTAB = 0x3D00

sym = {}
for line in open(os.path.join(ROOT, 'build', 'opticos.sym')):
    m = re.match(r'(\w+)\s+EQU\s+0?([0-9A-F]+)H', line)
    if m:
        sym[m.group(1)] = int(m.group(2), 16)

NEED = [
    'boot', 'ext_back', 'id_skip', 'ev_expr', 'ev_pop', 'ev_int',
    'err_type', 'err_syn', 'err_arg', 'err_nomem', 'LD_BYTES', 'T_LOAD',
    'xgo', 'x_rst', 'pop_int', 'push_u', 'err_rng', 'CLS', 'err_brk',
    'print_a', 'scroll', 'set_colour', 'po_oos',
]
missing = [k for k in NEED if k not in sym]
if missing:
    sys.exit('missing symbols: ' + ', '.join(missing))

# Attribute tables (same rule as phase 1)
def ta(i):
    ink, paper = i >> 4, i & 15
    br = (ink & 8) if (ink & 7) else (paper & 8)
    return (64 if br else 0) | (paper & 7) << 3 | (ink & 7)

def db(vals):
    return ''.join('        db ' + ','.join('$%02X' % v for v in vals[i:i + 16]) + '\n'
                   for i in range(0, len(vals), 16))

open(os.path.join(HERE, 'ta.inc'), 'w').write(db([ta(i) for i in range(256)]))
open(os.path.join(HERE, 'ta2.inc'), 'w').write(db([
    (64 if c & 8 else 0) | (c & 7) << 3 | (c & 7) for c in range(16)]))
open(os.path.join(HERE, 'os.inc'), 'w').write(
    '; generated by ext128/build.py from build/opticos.sym\n' +
    ''.join('OS_%s equ $%04X\n' % (k, sym[k]) for k in NEED) +
    'OS_ERR_TAPE equ $1A\n')

src = open(SAY_SRC).read()
# Refresh every OS_* equate in the SAY header from this tree's symbols.
def refresh_equ(text, name, value):
    pat = re.compile(r'^OS_%s equ \$[0-9A-Fa-f]+\s*$' % re.escape(name), re.M)
    line = 'OS_%s equ $%04X' % (name, value)
    if pat.search(text):
        return pat.sub(line, text)
    return line + '\n' + text

for k in NEED:
    src = refresh_equ(src, k, sym[k])
# Any leftover header-only symbols (T_LOAD is in NEED)
src = refresh_equ(src, 'ERR_TAPE', 0x1A)

# IM 1: count FRAMES while this ROM is paged (SCREEN FLIP's HALT, and
# long DRAW/BOX with interrupts on).
old_im1 = """        org $0038               ; IM 1 while this ROM is paged (briefly): just return
        push af
        pop af
        ei
        ret
"""
new_im1 = """        org $0038               ; IM 1 while this ROM is paged: count FRAMES
        push af
        push hl
        ld hl,FRAMES
        inc (hl)
        jr nz,im_x
        inc l
        inc (hl)
        jr nz,im_x
        inc l
        inc (hl)
im_x:   pop hl
        pop af
        ei
        ret
"""
if old_im1 not in src:
    sys.exit('IM1 block not found in SAY source')
src = src.replace(old_im1, new_im1, 1)
# FRAMES is used by the new ISR; define it if the SAY source doesn't.
if re.search(r'^FRAMES\s+equ', src, re.M) is None:
    src = src.replace('CH_ADD  equ', 'FRAMES  equ $5C78\nCH_ADD  equ', 1)

# Hook entries for PLOT/CLS/POINT/DRAW (xgo) and far-return (x_rst).
hooks = """
        org OS_xgo+10
ret_x:  out (c),a               ; back to OpticOS at x_back (RET)
        jp ext_x
        org OS_x_rst+5
        ret                     ; the way back from a call into OpticOS
        org OS_ext_back+3       ; resume at the original ext_main (after the JP)
"""
needle = """        org OS_ext_back-2
        out (c),a               ; back to ROM 0: the next fetch is its ext_back
        jp ext_main             ; ext_back: OpticOS pages us in here
"""
if needle not in src:
    sys.exit('ext_back gadget not found')
src = src.replace(needle, needle + hooks, 1)

# Dispatch SCREEN, BOX and CIRCLE (all modes) before SAY.
old_disp = """ext_main:
        ld hl,(CH_ADD)          ; $01 type hash length name
        inc hl
        inc hl
        inc hl
        ld de,n_say
        call namecmp
        jp z,em_say
"""
new_disp = """ext_main:
        ld hl,(CH_ADD)          ; $01 type hash length name
        inc hl
        inc hl
        inc hl
        ld de,n_screen
        call namecmp
        jp z,es_scr
        ld de,n_box
        call namecmp
        jp z,es_box
        ld de,n_circle
        call namecmp
        jp z,es_circ
em_saychk:
        ld de,n_say
        call namecmp
        jp z,em_say
"""
if old_disp not in src:
    sys.exit('ext_main dispatch not found')
src = src.replace(old_disp, new_disp, 1)

# Include the screen-mode code before the AY table, and stop SAY's
# codeend from running into our tables.
# The generated source uses "        org 15616" for $3D00.
if '        org 15616' not in src:
    sys.exit('AY table org not found')
src = src.replace(
    '        org 15616',
    '        include "screen.asm"\n        org 15616',
    1)

merged = os.path.join(HERE, 'merged.asm')
open(merged, 'w').write(src)

out = os.path.join(ROOT, 'build', 'opticos128ext')
r = subprocess.run([PASMO, '--bin', 'merged.asm', out + '.bin', out + '.sym'],
                   cwd=HERE, capture_output=True, text=True)
if r.returncode != 0:
    sys.stderr.write(r.stdout + r.stderr)
    sys.exit('pasmo failed')
rom = open(out + '.bin', 'rb').read()
assert len(rom) <= 16384, len(rom)
open(out + '.rom', 'wb').write(rom + bytes(16384 - len(rom)))
os.remove(out + '.bin')

end = {}
for line in open(out + '.sym'):
    m = re.match(r'(\w+)\s+EQU\s+0?([0-9A-F]+)H', line)
    if m:
        end[m.group(1)] = int(m.group(2), 16)

# Free space is from the end of screen/SAY code to TA2 at $3B00, plus
# $3B10-$3BFF (after the 16-byte TA2) — TA occupies $3C00-$3CFF, AY $3D00-$3FFF.
code_end = end.get('n_box', end.get('codeend', 0))
# n_box is the last label before org $3B00; codeend is SAY's end (before include).
# The included screen.asm sits after codeend, so the last byte of code is
# just before $3B00.  Use the first of TA2 / $3B00 minus the highest code label.
# Safer: scan the ROM for the last non-zero byte below $3B00.
last = 0x3B00
for a in range(0x3B00 - 1, 0x1000, -1):
    if rom[a] != 0:
        last = a + 1
        break
free_main = 0x3B00 - last
free_ta2 = 0x3C00 - 0x3B10  # 16-byte TA2 at $3B00
free = free_main + free_ta2
print('opticos128ext.rom: code through $%04X, AY table $3D00-$3FFF, '
      '%d bytes free ($%04X-$3AFF + $3B10-$3BFF)' % (last, free, last))
print('  SAY codeend $%04X, TA2 $%04X, TA $%04X' % (
    end.get('codeend', 0), end.get('TA2', 0), end.get('TA', 0)))
if last > 0x3B00:
    sys.exit('screen/SAY code ran into TA2 at $3B00')
if end.get('TA2') != 0x3B00 or end.get('TA') != 0x3C00:
    sys.exit('table addresses moved: TA2=%s TA=%s' % (end.get('TA2'), end.get('TA')))
