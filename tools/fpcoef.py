#!/usr/bin/env python3
"""fpcoef.py - derive OpticOS maths constants and polynomial coefficients
(clean room: Chebyshev fits computed here with mpmath, nothing taken from
any other ROM) and write them as 5-byte floats into src/gen/*.inc.

Format (spec 4.2, Sinclair-compatible layout): exponent byte e (bias 128,
value = 0.1mmm... x 2^(e-128)), then 4 mantissa bytes, most significant
first, with the implicit leading 1 replaced by the sign bit.
"""
import os
import mpmath as mp
mp.mp.dps = 50
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'src', 'gen')

def pack(v):
    """Nearest 5-byte float (round half up on the 32-bit mantissa)."""
    v = mp.mpf(v)
    if v == 0: return bytes(5)
    s = 0x80 if v < 0 else 0
    v = abs(v)
    e = int(mp.floor(mp.log(v, 2))) + 1        # v in [2^(e-1), 2^e)
    m = v / mp.mpf(2) ** e
    while m >= 1: m /= 2; e += 1
    while m < 0.5: m *= 2; e -= 1
    n = int(mp.floor(m * 2 ** 32 + mp.mpf('0.5')))
    if n == 2 ** 32: n //= 2; e += 1
    assert 2 ** 31 <= n < 2 ** 32 and -127 <= e <= 127
    return bytes([e + 128, ((n >> 24) & 0x7F) | s, (n >> 16) & 255, (n >> 8) & 255, n & 255])

def unpack(b):
    if b[0] == 0: raise ValueError
    n = ((b[1] | 0x80) << 24) | (b[2] << 16) | (b[3] << 8) | b[4]
    v = mp.mpf(n) / 2 ** 32 * mp.mpf(2) ** (b[0] - 128)
    return -v if b[1] & 0x80 else v

def hi_bits(v, bits):
    """v rounded to `bits` significant bits (for Cody-Waite splits)."""
    e = int(mp.floor(mp.log(abs(v), 2))) + 1
    q = mp.mpf(2) ** (e - bits)
    return mp.nint(v / q) * q

PI2 = mp.pi / 2
PI2H = hi_bits(PI2, 16)
LN2 = mp.log(2)
LN2H = hi_bits(LN2, 24)
# sqrt seed: a*m + b on [0.25, 1]
SQ = mp.chebyfit(mp.sqrt, [0.25, 1], 2)
CONST = [
    ('ONE', 1), ('HALF', mp.mpf(1) / 2), ('TWOPI', 2 / mp.pi), ('PI2H', PI2H), ('PI2L', PI2 - PI2H),
    ('PI2', PI2), ('PI6', mp.pi / 6), ('SQ3', mp.sqrt(3)), ('LOG2E', 1 / LN2), ('LN2H', LN2H),
    ('LN2L', LN2 - LN2H), ('LN10I', 1 / mp.log(10)), ('SQA', SQ[0]), ('SQB', SQ[1]), ('TEN', 10),
    ('E8', 10 ** 8), ('E9', 10 ** 9), ('TAN15', mp.tan(mp.pi / 12)), ('PI', mp.pi),
]
assert len(CONST) <= 26
def sinc(z): return mp.sin(mp.sqrt(z)) / mp.sqrt(z) if z else mp.mpf(1)
def atnc(z): return mp.atan(mp.sqrt(z)) / mp.sqrt(z) if z else mp.mpf(1)
def lnc(z): return 2 * mp.atanh(mp.sqrt(z)) / mp.sqrt(z) if z else mp.mpf(2)
S = (mp.sqrt(2) - 1) / (mp.sqrt(2) + 1)
POLYS = [   # name, function, interval, number of coefficients
    ('sin', sinc, [0, (mp.pi / 4) ** 2], 5),
    ('cos', lambda z: mp.cos(mp.sqrt(z)), [0, (mp.pi / 4) ** 2], 6),
    ('atn', atnc, [0, mp.tan(mp.pi / 12) ** 2], 6),
    ('ln', lnc, [0, (S * mp.mpf('1.0001')) ** 2], 5),
    ('exp', mp.exp, [-LN2 / 2 * mp.mpf('1.0001'), LN2 / 2 * mp.mpf('1.0001')], 9),
]

def db(b): return '        defb ' + ','.join('$%02X' % x for x in b)

def main():
    os.makedirs(GEN, exist_ok=True)
    out = ['; generated by tools/fpcoef.py - constants (5-byte floats)', 'kt_tab:']
    for i, (name, v) in enumerate(CONST):
        out.append(db(pack(v)) + '   ; K_%s = %s' % (name, mp.nstr(mp.mpf(v), 12)))
    eq = ['; generated by tools/fpcoef.py - byte-code source numbers of the constants']
    for i, (name, v) in enumerate(CONST):
        eq.append('K_%-6s equ %d' % (name, 6 + i))
    open(os.path.join(GEN, 'kconst.inc'), 'w').write('\n'.join(out) + '\n')
    open(os.path.join(GEN, 'kequ.inc'), 'w').write('\n'.join(eq) + '\n')
    for name, f, iv, n in POLYS:
        c, err = mp.chebyfit(f, iv, n, error=True)
        lines = ['; generated by tools/fpcoef.py - %s: %d coefficients, highest power first,' % (name, n),
                 '; Chebyshev fit on [%s, %s], max abs error %s' % (mp.nstr(iv[0], 6), mp.nstr(iv[1], 6), mp.nstr(err, 3))]
        for k in c:
            lines.append(db(pack(k)) + '   ; %s' % mp.nstr(k, 15))
        open(os.path.join(GEN, 'poly_%s.inc' % name), 'w').write('\n'.join(lines) + '\n')
    print('fpcoef: %d constants, %d polynomials (%d coefficients)' %
          (len(CONST), len(POLYS), sum(p[3] for p in POLYS)))

if __name__ == '__main__':
    main()
