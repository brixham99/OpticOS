#!/usr/bin/env python3
"""Generate src/gen/tokens.inc: keyword tokens ($80+), the bit-7 keyword
table, the statement jump table and the function tables (spec 5.2).
Statements come first so they dispatch by token-$80."""
import os
STMTS = ('PRINT LET IF ELSEIF ELSE ENDIF WHILE WEND REPEAT UNTIL FOR NEXT DEF ENDPROC ENDFN RETURN '
         'LOCAL TRY CATCH ENDTRY ERROR END STOP REM DIM CLS RUN LIST NEW BORDER OVER INVERSE BRIGHT FLASH PAPER INK POKE WAIT '
         'RANDOMIZE LOAD AUTO INPUT DATA READ RESTORE SAVE VERIFY PLOT DRAW BEEP OUT DPOKE CALL SWAP').split()
OTHER = 'THEN TO STEP PROC FN AND OR XOR NOT DIV MOD AT TAB CODE'.split()
FNUM = 'SQR SIN COS TAN ATN EXP LN LOG INT ABS SGN'.split()      # numeric, one argument
FOTH = 'PI RND LEN LEFT$ RIGHT$ MID$ CHR$ ASC STR$ VAL PEEK ERR TRUE FALSE INKEY$ FRAMES MAX MIN INSTR STRING$ HEX$ UPPER$ ERR$ IN USR DPEEK JOY'.split()
LINKED = 'IF ELSEIF ELSE WHILE WEND UNTIL TRY CATCH DEF'.split()        # followed by a $07 link slot
ALL = STMTS + OTHER + FNUM + FOTH
assert len(ALL) <= 128
def lab(w): return w.replace('$', 'S')
def main():
    L = ['; generated by tools/mktokens.py - do not edit']
    for i, w in enumerate(ALL): L.append('T_%-10s equ $%02X' % (lab(w), 0x80 + i))
    L += ['T_NSTMT    equ %d' % len(STMTS), 'T_LE       equ $08', 'T_GE       equ $09', 'T_NE       equ $0A',
          'T_SHL      equ $0B', 'T_SHR      equ $0C']
    L.append('kw_tab:')
    for w in ALL: L.append('        defb %s' % ','.join(["'%s'" % c for c in w[:-1]] + ["'%s'+$80" % w[-1]]))
    L.append('        defb 0')
    open(os.path.join(os.path.dirname(__file__), '..', 'src', 'gen', 'tokens.inc'), 'w').write('\n'.join(L) + '\n')
    L = ['; generated by tools/mktokens.py - do not edit']
    L.append('st_tab:')
    for w in STMTS: L.append('        defw st_%s' % lab(w).lower())
    L.append('fnu_tab:')
    for w in FNUM: L.append('        defw fp_%s' % w.lower())
    L.append('fno_tab:')
    for w in FOTH: L.append('        defw f_%s' % lab(w).lower())
    L.append('lk_tab: defb ' + ','.join('T_' + w for w in LINKED) + ',0')
    open(os.path.join(os.path.dirname(__file__), '..', 'src', 'gen', 'tokdisp.inc'), 'w').write('\n'.join(L) + '\n')
if __name__ == '__main__': main()
